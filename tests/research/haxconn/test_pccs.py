"""Tests for src/trtutils/research/haxconn/_pccs.py -- the PCCS model and its fit."""

from __future__ import annotations

import itertools

import pytest

from tests.research.haxconn.conftest import XAVIER
from trtutils.research.haxconn import Calibration, PCCSModel, fit_pccs

pytestmark = pytest.mark.cpu

_DEMAND = [5.0, 10.0, 20.0, 30.0, 40.0, 50.0, 60.0, 70.0, 80.0, 90.0]
_EXTERNAL = [10.0, 20.0, 30.0, 40.0, 50.0, 60.0, 70.0, 80.0, 90.0, 100.0]


@pytest.mark.parametrize(
    ("x", "y", "speed"),
    [
        pytest.param(60.0, 0.0, 100.0, id="no-external-demand"),
        pytest.param(30.0, 80.0, 100.0 - 4.9 * 30.0 / 100.0, id="minor"),
        pytest.param(60.0, 20.0, 100.0 - 4.9 * 60.0 / 100.0, id="normal-before-drop"),
        pytest.param(60.0, 40.0, 100.0 - (60.0 + 40.0 - 87.2) * 1.11, id="normal-dropping"),
        pytest.param(60.0, 90.0, 100.0 - (60.0 + 45.3 - 87.2) * 1.11, id="normal-flat"),
        pytest.param(
            100.0,
            90.0,
            100.0 - (100.0 + 45.3 - 87.2) * 1.11 * (100.0 + 45.3 - 87.2) / 45.3,
            id="intensive-flat",
        ),
        pytest.param(200.0, 90.0, 5.0, id="clamped"),
    ],
)
def test_relative_speed_regions(x, y, speed) -> None:
    """Each PCCS region and piece predicts the speed of its equation."""
    gpu = XAVIER["gpu"]
    assert gpu.relative_speed(x, y) == pytest.approx(speed)
    assert gpu.slowdown(x, y) == pytest.approx(100.0 / speed)


@pytest.mark.parametrize("accelerator", ["gpu", "dla"])
def test_fit_recovers_a_known_model(accelerator) -> None:
    """A matrix generated by a model fits back to a model predicting it within 2.5 points."""
    model = XAVIER[accelerator]
    speed = [[model.relative_speed(x, y) for y in _EXTERNAL] for x in _DEMAND]
    calibration = Calibration(accelerator, _DEMAND, _EXTERNAL, speed)
    fitted = PCCSModel.from_calibration(calibration)
    assert fitted == fit_pccs(_DEMAND, _EXTERNAL, speed)
    errors = [
        abs(fitted.relative_speed(x, y) - model.relative_speed(x, y))
        for x, y in itertools.product(_DEMAND, _EXTERNAL)
    ]
    assert max(errors) < 2.5


def test_fit_without_contention_never_slows_down() -> None:
    """A matrix without any slowdown fits a model that predicts none."""
    fitted = fit_pccs(_DEMAND, _EXTERNAL, [[100.0] * len(_EXTERNAL)] * len(_DEMAND))
    assert all(fitted.slowdown(x, y) == 1.0 for x, y in itertools.product(_DEMAND, _EXTERNAL))


@pytest.mark.parametrize(
    ("demand", "external", "speed", "match"),
    [
        pytest.param([1.0, 2.0], [1.0], [[100.0, 100.0]], "must be 2x1", id="shape"),
        pytest.param([2.0, 1.0], [1.0], [[100.0], [100.0]], "ascending", id="descending"),
    ],
)
def test_fit_rejects_bad_matrices(demand, external, speed, match) -> None:
    """A matrix that does not match its axes, or unsorted axes, raises."""
    with pytest.raises(ValueError, match=match):
        fit_pccs(demand, external, speed)
